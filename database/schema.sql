BEGIN;

CREATE TABLE IF NOT EXISTS products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku text NOT NULL UNIQUE,
    name text NOT NULL,
    category text NOT NULL,
    price numeric(14, 2) NOT NULL CHECK (price >= 0),
    wholesale_price numeric(14, 2) NOT NULL DEFAULT 0 CHECK (wholesale_price >= 0),
    stock numeric(14, 3) NOT NULL DEFAULT 0 CHECK (stock >= 0),
    unit text NOT NULL DEFAULT 'Pcs',
    icon text NOT NULL DEFAULT '▤',
    tone text NOT NULL DEFAULT 'blue',
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE products ADD COLUMN IF NOT EXISTS wholesale_price numeric(14, 2) NOT NULL DEFAULT 0 CHECK (wholesale_price >= 0);

CREATE TABLE IF NOT EXISTS customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    phone text NOT NULL DEFAULT '',
    account_type text NOT NULL DEFAULT 'Retail',
    credit_enabled boolean NOT NULL DEFAULT false,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 46449),
    customer_id bigint REFERENCES customers(id) ON DELETE SET NULL,
    customer_name text NOT NULL,
    total numeric(14, 2) NOT NULL CHECK (total >= 0),
    paid numeric(14, 2) NOT NULL CHECK (paid >= 0),
    store_location text NOT NULL DEFAULT 'Mogogosiek',
    status text NOT NULL DEFAULT 'Complete',
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (receipt_number)
);
ALTER TABLE sales ADD COLUMN IF NOT EXISTS salesperson text NOT NULL DEFAULT '';
ALTER TABLE sales ADD COLUMN IF NOT EXISTS store_location text NOT NULL DEFAULT 'Mogogosiek';

CREATE TABLE IF NOT EXISTS sale_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id bigint NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
    product_id bigint REFERENCES products(id) ON DELETE SET NULL,
    product_name text NOT NULL,
    sku text NOT NULL,
    quantity numeric(14, 3) NOT NULL CHECK (quantity > 0),
    unit text NOT NULL,
    unit_price numeric(14, 2) NOT NULL CHECK (unit_price >= 0),
    line_total numeric(14, 2) NOT NULL CHECK (line_total >= 0)
);

CREATE TABLE IF NOT EXISTS sale_payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id bigint NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
    method text NOT NULL CHECK (method IN ('Cash', 'M-Pesa', 'EFT')),
    amount numeric(14, 2) NOT NULL CHECK (amount > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS module_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_name text NOT NULL,
    submodule_name text NOT NULL,
    record jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS held_sales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number bigint NOT NULL,
    customer_name text NOT NULL,
    items jsonb NOT NULL,
    payments jsonb NOT NULL DEFAULT '[]'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS staff_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL,
    username text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('Admin', 'Manager', 'Cashier', 'Stock Controller', 'Reports')),
    active boolean NOT NULL DEFAULT true,
    must_change_password boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sales_created_at_idx ON sales (created_at DESC);
CREATE INDEX IF NOT EXISTS module_entries_lookup_idx ON module_entries (module_name, submodule_name, created_at DESC);
CREATE INDEX IF NOT EXISTS staff_users_username_idx ON staff_users (lower(username));

CREATE OR REPLACE FUNCTION create_pos_sale(payload jsonb)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    requested_item jsonb;
    product_row products%ROWTYPE;
    new_sale sales%ROWTYPE;
    customer_row customers%ROWTYPE;
    item_quantity numeric(14, 3);
    item_total numeric(14, 2);
    stock_after numeric(14, 3);
    sale_total numeric(14, 2) := 0;
    paid_total numeric(14, 2) := 0;
    item_count integer := 0;
    payment_row jsonb;
    item_rows jsonb := '[]'::jsonb;
    payment_rows jsonb := '[]'::jsonb;
    customer_label text;
    store_location text;
BEGIN
    IF jsonb_typeof(payload->'items') IS DISTINCT FROM 'array' THEN
        RAISE EXCEPTION 'Sale items must be provided as a list.';
    END IF;
    IF jsonb_array_length(payload->'items') = 0 THEN
        RAISE EXCEPTION 'A sale must contain at least one product.';
    END IF;

    customer_label := NULLIF(btrim(payload->>'customer'), '');
    IF customer_label IS NULL THEN
        RAISE EXCEPTION 'Select a customer before completing this sale.';
    END IF;

    SELECT * INTO customer_row FROM customers WHERE name = customer_label AND active FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'The selected customer no longer exists. Refresh and try again.';
    END IF;

    FOR requested_item IN SELECT value FROM jsonb_array_elements(payload->'items')
    LOOP
        IF (requested_item->>'quantity') IS NULL OR (requested_item->>'quantity')::numeric <= 0 THEN
            RAISE EXCEPTION 'Product quantities must be greater than zero.';
        END IF;

        SELECT * INTO product_row
        FROM products
        WHERE id = (requested_item->>'productId')::bigint AND active
        FOR UPDATE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'A selected product is no longer active. Refresh the product list.';
        END IF;

        item_quantity := (requested_item->>'quantity')::numeric;
        IF product_row.stock < item_quantity THEN
            RAISE EXCEPTION 'Insufficient stock for %: % % available.', product_row.name, product_row.stock, product_row.unit;
        END IF;

        item_total := round(product_row.price * item_quantity, 2);
        sale_total := sale_total + item_total;
        item_count := item_count + 1;
        item_rows := item_rows || jsonb_build_array(jsonb_build_object(
            'productId', product_row.id,
            'name', product_row.name,
            'sku', product_row.sku,
            'quantity', item_quantity,
            'unit', product_row.unit,
            'price', product_row.price,
            'total', item_total
        ));
    END LOOP;

    IF jsonb_typeof(payload->'payments') = 'array' THEN
        FOR payment_row IN SELECT value FROM jsonb_array_elements(payload->'payments')
        LOOP
            IF payment_row->>'method' NOT IN ('Cash', 'M-Pesa', 'EFT') OR (payment_row->>'amount')::numeric < 0 THEN
                RAISE EXCEPTION 'A payment method or amount is invalid.';
            END IF;
            IF (payment_row->>'amount')::numeric > 0 THEN
                paid_total := paid_total + (payment_row->>'amount')::numeric;
                payment_rows := payment_rows || jsonb_build_array(jsonb_build_object(
                    'method', payment_row->>'method',
                    'amount', (payment_row->>'amount')::numeric
                ));
            END IF;
        END LOOP;
    END IF;

    IF paid_total < sale_total AND NOT customer_row.credit_enabled THEN
        RAISE EXCEPTION 'Full payment is required unless the selected customer has an approved credit account.';
    END IF;

    store_location := COALESCE(NULLIF(btrim(payload->>'storeLocation'), ''), 'Mogogosiek');
    IF store_location NOT IN ('Mogogosiek', 'Koiwa') THEN
        RAISE EXCEPTION 'Select a valid shop location.';
    END IF;

    INSERT INTO sales (customer_id, customer_name, total, paid, salesperson, store_location)
    VALUES (customer_row.id, customer_row.name, sale_total, paid_total, COALESCE(NULLIF(btrim(payload->>'salesperson'), ''), ''), store_location)
    RETURNING * INTO new_sale;

    FOR requested_item IN SELECT value FROM jsonb_array_elements(item_rows)
    LOOP
        INSERT INTO sale_items (sale_id, product_id, product_name, sku, quantity, unit, unit_price, line_total)
        VALUES (
            new_sale.id,
            (requested_item->>'productId')::bigint,
            requested_item->>'name',
            requested_item->>'sku',
            (requested_item->>'quantity')::numeric,
            requested_item->>'unit',
            (requested_item->>'price')::numeric,
            (requested_item->>'total')::numeric
        );
        UPDATE products
        SET stock = stock - (requested_item->>'quantity')::numeric
        WHERE id = (requested_item->>'productId')::bigint
        RETURNING stock INTO stock_after;

        INSERT INTO module_entries (module_name, submodule_name, record)
        VALUES (
            'Stock',
            'Counter Sales',
            jsonb_build_object(
                'fields', jsonb_build_array(
                    new_sale.created_at,
                    new_sale.receipt_number,
                    requested_item->>'name',
                    '-' || (requested_item->>'quantity'),
                    stock_after,
                    new_sale.customer_name
                ),
                'workflow', jsonb_build_object(
                    'type', 'stock-sale',
                    'receiptNumber', new_sale.receipt_number,
                    'productId', (requested_item->>'productId')::bigint,
                    'productName', requested_item->>'name',
                    'sku', requested_item->>'sku',
                    'quantity', (requested_item->>'quantity')::numeric,
                    'storeLocation', new_sale.store_location
                ),
                'stockMovement', jsonb_build_object(
                    'movement', 'sale',
                    'delta', -((requested_item->>'quantity')::numeric),
                    'productId', (requested_item->>'productId')::bigint,
                    'sku', requested_item->>'sku',
                    'productName', requested_item->>'name',
                    'stockAfter', stock_after,
                    'recordedBy', new_sale.salesperson,
                    'storeLocation', new_sale.store_location
                )
            )
        );
    END LOOP;

    FOR payment_row IN SELECT value FROM jsonb_array_elements(payment_rows)
    LOOP
        INSERT INTO sale_payments (sale_id, method, amount)
        VALUES (new_sale.id, payment_row->>'method', (payment_row->>'amount')::numeric);
    END LOOP;

    RETURN jsonb_build_object(
        'id', new_sale.id,
        'receiptNumber', new_sale.receipt_number,
        'customer', new_sale.customer_name,
        'total', new_sale.total,
        'paid', new_sale.paid,
        'balance', greatest(new_sale.total - new_sale.paid, 0),
        'salesperson', new_sale.salesperson,
        'storeLocation', new_sale.store_location,
        'status', new_sale.status,
        'createdAt', new_sale.created_at,
        'itemCount', item_count,
        'items', item_rows,
        'payments', payment_rows
    );
END;
$$;

